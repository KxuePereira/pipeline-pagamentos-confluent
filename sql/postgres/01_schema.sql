-- Todos os horários ficam em UTC, sem fuso, com precisão de milissegundo.
-- Com time.precision.mode=connect, o Debezium transforma TIMESTAMP(3) em
-- Avro long/timestamp-millis, que o Flink lê direto como tempo de evento.

CREATE TABLE IF NOT EXISTS customers (
    customer_id  INTEGER      PRIMARY KEY,
    full_name    TEXT         NOT NULL,          -- PII
    email        TEXT         NOT NULL,          -- PII
    city         TEXT         NOT NULL,
    state        CHAR(2)      NOT NULL,
    created_at   TIMESTAMP(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at   TIMESTAMP(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

CREATE TABLE IF NOT EXISTS accounts (
    account_id   INTEGER       PRIMARY KEY,
    customer_id  INTEGER       NOT NULL REFERENCES customers(customer_id),
    status       TEXT          NOT NULL CHECK (status IN ('ACTIVE', 'BLOCKED', 'CLOSED')),
    credit_limit NUMERIC(15,2) NOT NULL CHECK (credit_limit >= 0),
    risk_tier    TEXT          NOT NULL CHECK (risk_tier IN ('LOW', 'MEDIUM', 'HIGH')),
    created_at   TIMESTAMP(3)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at   TIMESTAMP(3)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

CREATE TABLE IF NOT EXISTS cards (
    card_id      INTEGER      PRIMARY KEY,
    account_id   INTEGER      NOT NULL REFERENCES accounts(account_id),
    pan_last4    CHAR(4)      NOT NULL,          -- PCI (só os 4 últimos dígitos, nunca o PAN)
    brand        TEXT         NOT NULL,
    status       TEXT         NOT NULL CHECK (status IN ('ACTIVE', 'BLOCKED')),
    created_at   TIMESTAMP(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at   TIMESTAMP(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

CREATE TABLE IF NOT EXISTS merchants (
    merchant_id  INTEGER      PRIMARY KEY,
    name         TEXT         NOT NULL,
    mcc          CHAR(4)      NOT NULL,          -- Merchant Category Code
    category     TEXT         NOT NULL,
    city         TEXT         NOT NULL,
    country      CHAR(2)      NOT NULL,
    created_at   TIMESTAMP(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at   TIMESTAMP(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

CREATE TABLE IF NOT EXISTS transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id        INTEGER       NOT NULL REFERENCES cards(card_id),
    account_id     INTEGER       NOT NULL REFERENCES accounts(account_id),
    merchant_id    INTEGER       NOT NULL REFERENCES merchants(merchant_id),
    amount         NUMERIC(15,2) NOT NULL CHECK (amount > 0),
    currency       CHAR(3)       NOT NULL DEFAULT 'BRL',
    channel        TEXT          NOT NULL CHECK (channel IN ('POS', 'ECOMMERCE', 'CONTACTLESS')),
    status         TEXT          NOT NULL CHECK (status IN ('APPROVED', 'DECLINED')),
    created_at     TIMESTAMP(3)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

CREATE INDEX IF NOT EXISTS idx_transactions_card_time ON transactions (card_id, created_at);

-- updated_at automático: sem isso o UPDATE do CDC chegaria com o horário antigo
-- e a versão nova da conta "nasceria no passado" no temporal join do Flink.
CREATE OR REPLACE FUNCTION touch_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at := (now() AT TIME ZONE 'utc');
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['customers', 'accounts', 'cards', 'merchants'] LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_touch ON %1$s', t);
        EXECUTE format('CREATE TRIGGER trg_%1$s_touch BEFORE UPDATE ON %1$s
                        FOR EACH ROW EXECUTE FUNCTION touch_updated_at()', t);
    END LOOP;
END $$;
